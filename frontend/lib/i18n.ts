export function createLocaleRuntime(options: LocaleOptions = {}) {
  const merged = {
    en: { ...catalogs.en, ...(options.catalogs?.en ?? {}) },
    "zh-CN": { ...catalogs["zh-CN"], ...(options.catalogs?.["zh-CN"] ?? {}) },
  } satisfies Record<FrontendLocale, Record<string, string>>;
  let persisted = options.storedLocale;
  if (persisted === undefined) {
    try { persisted = options.storage?.getItem(LOCALE_STORAGE_KEY); } catch { persisted = undefined; }
  }
  let locale: FrontendLocale = isLocale(persisted)
    ? persisted
    : options.navigatorLanguage?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
  const subscribers = new Set<(locale: FrontendLocale) => void>();
  return Object.freeze({
    get locale() { return locale; },
    t(key: string) {
      const value = merged[locale][key] ?? merged.en[key];
      if (value !== undefined && value !== key && value !== "undefined" && value !== "null") return value;
      if (key.startsWith("NAV_")) return navigationFallbacks[locale][key] ?? (locale === "zh-CN" ? "导航" : "Navigation");
      return String(key);
    },
    setLocale(next: string) {
      if (!isLocale(next) || next === locale) return false;
      locale = next;
      try { options.storage?.setItem(LOCALE_STORAGE_KEY, next); } catch { /* optional storage */ }
      for (const subscriber of subscribers) subscriber(locale);
      return true;
    },
    subscribe(subscriber: (locale: FrontendLocale) => void) {
      subscribers.add(subscriber);
      return () => subscribers.delete(subscriber);
    },
  });
}

export function frontendText(locale: Pick<LocaleRuntime, "t"> | undefined, key: string): string {
  return locale?.t(key) ?? catalogs.en[key] ?? key;
}

export interface FrontendPaginationLabels {
  navigationLabel: string;
  totalLabel: string;
  rangeLabel: string;
  pageSizeLabel: string;
  previousLabel: string;
  nextLabel: string;
  pageLabel(page: number): string;
  mobileSummary(page: number, totalPages: number): string;
}

export type DataPaginationLocalization = { locale: Pick<LocaleRuntime, "t">; labels?: never } | { labels: FrontendPaginationLabels; locale?: never };

export function frontendPaginationLabels(locale: Pick<LocaleRuntime, "t">): FrontendPaginationLabels {
  return {
    navigationLabel: frontendText(locale, "PAGINATION_NAVIGATION"),
    totalLabel: frontendText(locale, "PAGINATION_TOTAL"),
    rangeLabel: frontendText(locale, "PAGINATION_VISIBLE"),
    pageSizeLabel: frontendText(locale, "PAGINATION_ROWS_PER_PAGE"),
    previousLabel: frontendText(locale, "PAGINATION_PREVIOUS_PAGE"),
    nextLabel: frontendText(locale, "PAGINATION_NEXT_PAGE"),
    pageLabel: (page) => formatFrontendText(locale, "PAGINATION_PAGE_LABEL", { page }),
    mobileSummary: (page, totalPages) => formatFrontendText(locale, "PAGINATION_MOBILE_SUMMARY", { page, totalPages }),
  };
}

function formatFrontendText(locale: Pick<LocaleRuntime, "t">, key: string, values: Record<string, number>): string {
  return frontendText(locale, key).replace(/\{(\w+)\}/gu, (_, name: string) => String(values[name] ?? ""));
}

function isLocale(value: unknown): value is FrontendLocale {
  return value === "en" || value === "zh-CN";
}
